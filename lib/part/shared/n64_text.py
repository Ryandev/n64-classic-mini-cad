def loop_to_prism(outer: Loop, inners: tuple[Loop, ...], z0: float, height: float) -> cq.Shape:
    """Extrude a 2D XY outer wire (with optional inner counter-hole wires) along `+Z`."""
    ow = cq.Workplane("XY", origin=(0.0, 0.0, z0)).polyline(list(outer)).close().wire().val()
    iws = [
        cq.Workplane("XY", origin=(0.0, 0.0, z0)).polyline(list(iw)).close().wire().val()
        for iw in inners
    ]
    face = cq.Face.makeFromWires(ow, iws)
    return cq.Solid.extrudeLinear(face, cq.Vector(0.0, 0.0, height))


PLAQUE_TEXT = "CLASSIC"
# Sized to the oval's inner ring (X -8.53..8.53, Y 37.03..40.39): about 11.8 x 2.0 mm.
PLAQUE_FONT_SIZE = 2.6
PLAQUE_CENTRE = (0.0, 38.71)
_FONT = Path(__file__).with_name("fonts") / "DejaVuSans-Bold.ttf"
# The owner's own plaque letters, kept out of the published repo (git-ignored `cad/local/`).
_LOCAL_GLYPHS = Path(__file__).resolve().parents[3] / "local" / "nintendo_glyphs.py"


def _local_glyphs() -> tuple[GlyphLoops, ...] | None:
    # N64_PUBLIC=1 forces the public CLASSIC lettering even on the owner's machine: anything
    # rendered for the published repo (README pictures) must never carry the private letters.
    if os.environ.get("N64_PUBLIC") == "1" or not _LOCAL_GLYPHS.is_file():
        return None
    spec = importlib.util.spec_from_file_location("local_nintendo_glyphs", _LOCAL_GLYPHS)
    if spec is None or spec.loader is None:
        raise ImportError(f"cannot load {_LOCAL_GLYPHS}")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.NINTENDO_GLYPHS


def plaque_text_prisms(z0: float, height: float) -> list[cq.Shape]:
    """`PLAQUE_TEXT` in the bundled DejaVu Sans Bold, centred in the rear oval plaque."""
    if not _FONT.is_file():
        raise FileNotFoundError(f"plaque font missing: {_FONT}")
    text = (
        cq.Workplane("XY", origin=(PLAQUE_CENTRE[0], PLAQUE_CENTRE[1], z0))
        .text(
            PLAQUE_TEXT,
            PLAQUE_FONT_SIZE,
            height,
            fontPath=str(_FONT),
            halign="center",
            valign="center",
        )
        .val()
    )
    return list(text.Solids())


def nintendo_plaque_prisms(z0: float = 25.0, height: float = 10.0) -> list[cq.Shape]:
    """Vertical cutting prisms for the rear stadium oval ring and its lettering.

    The lettering is `PLAQUE_TEXT` unless the owner's git-ignored `cad/local/nintendo_glyphs.py`
    exists, in which case its traced script letters are engraved instead.
    """
    sols = [loop_to_prism(NINTENDO_PLAQUE_LOOP[0], NINTENDO_PLAQUE_LOOP[1], z0, height)]
    glyphs = _local_glyphs()
    if glyphs is None:
        return sols + plaque_text_prisms(z0, height)
    return sols + [loop_to_prism(outer, inners, z0, height) for outer, inners in glyphs]


